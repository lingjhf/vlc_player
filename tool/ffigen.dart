import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = root.resolve('src/native/vlc_player_transport.h');
  final libclang = Platform.environment['VLC_PLAYER_LIBCLANG'];
  await FfiGenerator(
    input: Input(entryPoints: [header], include: (file) => file == header),
    visitors: [
      Visitor(
        func: (function) {
          function.isIncluded = function.originalName == 'vlc_player_dispatch';
        },
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/vlc_player_bindings.g.dart'),
      ),
      preamble: '''
// Copyright (c) 2026 lingjhf
// SPDX-License-Identifier: MIT
// Generated by package:ffigen. Do not edit manually.''',
      style: const DynamicLibraryBindings(
        wrapperName: 'VlcPlayerNativeBindings',
        wrapperDocComment: 'Native playback transport for Windows and Android.',
      ),
    ),
  ).generate(libclangDylib: libclang == null ? null : Uri.file(libclang));
}
